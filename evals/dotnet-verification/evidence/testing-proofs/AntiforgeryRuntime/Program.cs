using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.TestHost;
var builder = WebApplication.CreateBuilder(args);
builder.WebHost.UseTestServer(); builder.Services.AddAntiforgery();
await using var app = builder.Build(); app.UseAntiforgery();
app.MapPost("/attribute", Handler);
app.MapPost("/form-binding", ([FromForm] string message) => message);
await app.StartAsync(); var client=app.GetTestClient();
var response=await client.PostAsync("/attribute", new FormUrlEncodedContent(new Dictionary<string,string>{{"message","executed-without-token"}}));
Console.WriteLine("MVC attribute Minimal endpoint: " + (int)response.StatusCode + " " + await response.Content.ReadAsStringAsync());
if ((int)response.StatusCode != 200) throw new Exception("Unexpected attribute behavior");
var control=await client.PostAsync("/form-binding", new FormUrlEncodedContent(new Dictionary<string,string>{{"message","blocked"}}));
Console.WriteLine("Native form-binding control: " + (int)control.StatusCode);
if ((int)control.StatusCode != 400) throw new Exception("Expected automatic validation control");
[ValidateAntiForgeryToken] static string Handler(HttpRequest request) => request.Form["message"].ToString();
